// ============================================================
// 🧠 القرارات لوحدها — من غير Firebase
// ============================================================
// ⚠️⚠️ ليه الملف ده منفصل: الدوال اللي تحت هي **كل المنطق** اللي ممكن
// يغلط (امتى نبعت، ومين ياخد، ونكتب إيه). ولو كانت متعشّشة جوه المشغّل
// نفسه، مفيش طريقة نفحصها من غير ما نشغّل السحابة كلها.
//
// هنا بتتفحص كلها بجافاسكريبت عادي، من غير شبكة ولا حساب ولا فلوس.

// بيتبعت إشعار **بس** لما الدرجة تتحوّل لـ"معلّق" — مش مع كل تعديل.
//
// ⚠️ الشرط `before !== 'pending'` مهم: من غيره أي تعديل على درجة
// معلّقة (تغيير الكمية المطلوبة مثلًا) كان هيطلّع إشعار جديد.
function becamePending(before, after) {
  const was = before && before.status;
  const now = after && after.status;
  return now === 'pending' && was !== 'pending';
}

// ============================================================
// ⏱️⚠️⚠️ الخنق **اتشال** — وده المكان اللي كان فيه
// ============================================================
// كان: إشعار واحد كل دقيقة، والباقي بيتسكت عنه. والسبب كان معقول —
// طلب التزويد الواحد ممكن يخلي عشرين درجة معلّقة في نفس اللحظة، وده
// عشرين إشعار على تليفون واحد في ثانية.
//
// اتشال بطلب صريح: "عاوز اي طلب تزويد يطلب يوصل رسالة يعني كل طلب
// يوصل رسالة مش يستني دقيقة".
//
// ⚠️ والمشكلة اللي كان بيحلها الخنق **اتحلّت بطريقة أحسن**: التجميع.
// بدل ما نسكت عن الطلب التاني، بنبعت إشعار جديد فيه **كل** الدرجات
// المعلّقة في الفئة، والتليفون بيستبدل القديم بيه (نفس الوسم للفئة).
//
// فالنتيجة اللي المستخدم بيشوفها: إشعار واحد للفئة، بيتحدّث مع كل
// طلب جديد ويكبر — مش عشرين إشعار، ومش سكوت.
// وده بالظبط اللي اتطلب: "لما وصل 6 يكتب درجة 5 و 6".

// ============================================================
// 🧾 قايمة الدرجات في سطر واحد
// ============================================================
// ⚠️ بسقف: فئة فيها 40 درجة معلّقة هتطلّع سطر مالوش آخر، والإشعار
// بيتقص على التليفون. بنعرض أول كام واحدة ونقول الباقي كام.
const MAX_LISTED_GRADES = 6;

function formatGradeList(numbers) {
  const clean = (Array.isArray(numbers) ? numbers : [])
    .map((n) => Number(n))
    .filter((n) => isFinite(n))
    // ⚠️ من غير تكرار ومرتّبة: الدرجات بتيجي من استعلام مش مضمون ترتيبه،
    // و"5 و 6" أوضح بكتير من "6 و 5".
    .filter((n, i, a) => a.indexOf(n) === i)
    .sort((a, b) => a - b);
  if (!clean.length) return '';
  if (clean.length === 1) return `درجة ${clean[0]}`;
  const shown = clean.slice(0, MAX_LISTED_GRADES);
  const rest = clean.length - shown.length;
  const list = shown.join('، ');
  return rest > 0 ? `درجات ${list} و${rest} غيرهم` : `درجات ${list}`;
}

// ============================================================
// 👤 مين ياخد الإشعار
// ============================================================
// ⚠️⚠️ **مابنعيدش كتابة جدول الصلاحيات هنا.** الجدول موجود في مكانين
// خلاص (permissions.js وfirestore.rules)، ونسخة تالتة معناها إنها
// هتختلف عنهم يوم ما حد يعدّل واحد وينسى التاني.
//
// بدل كده: الجهاز نفسه بيكتب `wantsRestock` وقت ما يسجّل — وهو عارف
// صلاحية صاحبه لأنه مشترك عليها لايف.
//
// والحارس الوحيد هنا لحالة واحدة: **الصلاحية اتقفلت بالاسم**. ساعتها
// الملف الشخصي فيه `perms.editMainQty === false` صراحةً، وده بنحترمه
// فورًا من غير ما نستنى الجهاز يفتح.
function tokenIsEligible(tokenDoc, profile) {
  if (!tokenDoc || tokenDoc.wantsRestock !== true) return false;
  const perms = (profile && profile.perms) || {};
  if (perms.editMainQty === false) return false;
  return true;
}

// ⚠️ نفس الوسم اللي الإشعار المحلي بيستخدمه — فالتليفون بيستبدل
// القديم بدل ما يكوّم إشعارات فوق بعض.
const PUSH_TAG = 'tazweed-restock';

// نص الإشعار. بنسمّي الفئة لأن ده أول سؤال هيسأله: "تزويد إيه؟"
function buildMessage(categoryName, gradeNumber) {
  const cat = String(categoryName || '').trim();
  const num = gradeNumber === 0 || gradeNumber ? String(gradeNumber) : '';
  return {
    title: '🔔 طلب تزويد جديد',
    body: cat ? (num ? `${cat} — درجة ${num}` : cat) : 'فيه طلب تزويد مستني',
  };
}

// ============================================================
// 🔔 الإشعار المجمّع — كل الدرجات المعلّقة في الفئة
// ============================================================
// اتطلب بالنص: "لو في طلب تزويد من الكريب السادة درجة 5 وبعدين طلبت
// درجة 6 لما يوصل اشعار 6 تبقي في الاشعارات ... يكتب درجة 5 و 6".
//
// ⚠️ العنوان بيقول العدد لما يبقى أكتر من واحدة: ده الفرق بين "فيه
// طلب" و"فيه أربع طلبات مستنيين" — والرقم ده هو اللي بيخلي الواحد
// يقوم دلوقتي مش بعدين.
function buildGroupedMessage(categoryName, numbers) {
  const cat = String(categoryName || '').trim();
  const list = formatGradeList(numbers);
  const count = (Array.isArray(numbers) ? numbers : []).filter((n) => isFinite(Number(n))).length;
  const title = count > 1 ? `🔔 ${count} طلبات تزويد` : '🔔 طلب تزويد جديد';
  if (!cat) return { title, body: list || 'فيه طلب تزويد مستني' };
  return { title, body: list ? `${cat} — ${list}` : cat };
}

// ============================================================
// 🏷️ وسم لكل فئة على حدة
// ============================================================
// ⚠️⚠️ ده اللي بيخلي التجميع يبان فعلًا: التليفون بيستبدل الإشعار
// اللي ليه **نفس الوسم**. فوسم واحد للفئة معناه إن طلب الدرجة 6
// بيحلّ محل إشعار الدرجة 5 ويكتب الاتنين — بدل ما يتكوّم فوقه.
//
// ⚠️ ولكل فئة وسم لوحدها: لو كلهم بوسم واحد، طلب في فئة تانية كان
// هيمسح إشعار الفئة الأولى وكإنه اتزوّد.
function categoryTag(categoryId) {
  const id = String(categoryId || '').trim();
  return id ? `${PUSH_TAG}-${id}` : PUSH_TAG;
}


module.exports = {
  becamePending,
  tokenIsEligible,
  buildMessage,
  buildGroupedMessage,
  formatGradeList,
  categoryTag,
  MAX_LISTED_GRADES,
  PUSH_TAG,
};
