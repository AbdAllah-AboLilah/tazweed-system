const LABEL_FONT_DEFAULT = 'system';
const LABEL_FONT_KEY = 'tazweed_label_font';

function labelFontById(id) {
  return LABEL_FONTS.find((f) => f.id === id) || null;
}

// ⚠️ نفس ترتيب الأولوية بتاع getPrintNameMm بالحرف: الإعداد الجاي من
// بعيد بيكسب، وبعده المحفوظ على الجهاز، وبعده الافتراضي. أي ترتيب تاني
// معناه إن "إرسال إعدادات الطابعة" من التليفون مالوش أثر.
function getLabelFontId() {
  let remote;
  try {
    remote = typeof readPrintField === 'function' ? readPrintField('labelFont') : undefined;
  } catch (err) {
    remote = undefined;
  }
  if (remote !== undefined && remote !== null && remote !== '' && labelFontById(remote)) {
    return remote;
  }
  try {
    const v = localStorage.getItem(LABEL_FONT_KEY);
    if (v && labelFontById(v)) return v;
  } catch (err) {
    /* تجاهل */
  }
  return LABEL_FONT_DEFAULT;
}

function setLabelFontId(id) {
  const font = labelFontById(id) ? id : LABEL_FONT_DEFAULT;
  try {
    localStorage.setItem(LABEL_FONT_KEY, font);
  } catch (err) {
    console.warn('تعذّر حفظ خط الملصق:', err);
  }
  try {
    if (typeof saveMachineSetting === 'function') {
      saveMachineSetting({ labelFont: font }, 'خط الملصق');
    }
  } catch (err) {
    console.warn('تعذّر حفظ خط الملصق المشترك:', err);
  }
  // الخط اتغيّر → اللي اتأكدنا إنه محمّل بقى قديم.
  if (labelFontReadyId !== font) labelFontReadyId = '';
  // ونبدأ تنزيله فورًا عشان المعاينة الجاية تبقى بيه، مش بخط الجهاز.
  try {
    ensureLabelFontReady();
  } catch (err) {
    /* تجاهل */
  }
}

// بترجّع كائن الخط المختار، أو null لو "خط الجهاز".
function activeLabelFont() {
  const f = labelFontById(getLabelFontId());
  return f && f.family ? f : null;
}

// ============================================================
// ⭐⭐⭐ الحارس: مانرسمش بخط لسه مانزلش
// ============================================================
// ⚠️⚠️ الكانفاس **مابيطلبش** الخط. لو كتبت ctx.font = '...TZ Cairo'
// والملف لسه مانزلش، المتصفح بيرسم بخط بديل **من غير أي خطأ** — يعني
// ملصق مطبوع بخط غير اللي المستخدم اختاره، وهو مش واخد باله.
//
// وده أخطر من إنه يقع: لو وقع كنا هنعرف.
//
// فالقاعدة: `labelFontStack` مابترجّعش الخط المختار إلا لو `labelFontReadyId`
// بيساويه — يعني إحنا **اتأكدنا بنفسنا** إنه محمّل. غير كده بترجّع خط
// الجهاز، وده أسوأ حاجة ممكن تحصل: الملصق يطلع زي ما كان قبل المفتاح.
//
// ⚠️ والأهم: القياس والرسم بيقرأوا من **نفس** الدالة، فمستحيل واحد
// يقيس بخط والتاني يرسم بخط تاني — وده بالظبط العطل اللي الملف ده
// اتعمل عشانه.
let labelFontReadyId = '';

async function ensureLabelFontReady() {
  const f = activeLabelFont();
  if (!f) {
    labelFontReadyId = '';
    return true; // خط الجهاز — مافيش حاجة تتحمّل
  }
  if (labelFontReadyId === f.id) return true;
  if (typeof document === 'undefined' || !document.fonts || !document.fonts.load) {
    return false;
  }
  // ⚠️ النص ده مقصود إنه فيه عربي **وأرقام**: الخط مقسوم لملفين
  // (عربي/لاتيني)، وطلب العربي لوحده بينزّل ملف واحد بس — وبعدين
  // الأرقام بتترسم بخط الجهاز. الملصق كله أرقام (الباركود والسعر).
  const probe = 'اختبار 0123';
  const bold = f.boldWeight || 700;
  try {
    await Promise.all([
      document.fonts.load(`400 100px "${f.family}"`, probe),
      document.fonts.load(`${bold} 100px "${f.family}"`, probe),
    ]);
  } catch (err) {
    console.warn('تعذّر تحميل خط الملصق:', err);
    return false;
  }
  const ok =
    document.fonts.check(`400 100px "${f.family}"`, probe) &&
    document.fonts.check(`${bold} 100px "${f.family}"`, probe);
  labelFontReadyId = ok ? f.id : '';
  if (!ok) console.warn('خط الملصق مانزلش — هنطبع بخط الجهاز.');
  return ok;
}

// ============================================================
// ⭐ الدالة اللي كل مكان في الملصق بيعدّي منها
// ============================================================
// `base` هو نص الخطوط اللي كان مكتوب في المكان ده **بالحرف** قبل
// الملف ده. ولما الإعداد يكون على "خط الجهاز"، بترجّعه زي ما هو
// بالظبط — مفيش حرف بيتغيّر.
//
// ⚠️ متشيلش `base` من آخر النص لما يكون فيه خط مختار: ده احتياطي لو
// الخط فشل يترسم لأي سبب (ملف بايظ، ذاكرة، متصفح قديم).
function labelFontStack(base) {
  const f = activeLabelFont();
  if (!f || labelFontReadyId !== f.id) return base;
  return `'${f.family}', ${base}`;
}

// ============================================================
// @font-face للمستندات المطبوعة (نافذة/إطار مستقل)
// ============================================================
// ⚠️⚠️ الروابط **لازم** تبقى مطلقة. المستند المطبوع بيتبني كنص HTML
// كامل وبيتحط في إطار مالوش عنوان (srcdoc) — فأي رابط نسبي زي
// `./fonts/x.woff2` مالوش أصل يتحسب منه وبيفشل في صمت.
//
// ⚠️ وبترجّع نص فاضي على "خط الجهاز" — عشان المستند المطبوع يفضل
// **متطابق بايت ببايت** مع اللي كان بيتبعت قبل المفتاح ده.
function labelFontBase() {
  try {
    return new URL('./fonts/', location.href).href;
  } catch (err) {
    return './fonts/';
  }
}

function labelFontFaceCSS() {
  const f = activeLabelFont();
  if (!f || labelFontReadyId !== f.id) return '';
  const base = labelFontBase();
  let css = '';
  f.files.forEach((row) => {
    css +=
      `@font-face{font-family:'${f.family}';font-style:normal;font-weight:${row.weight};` +
      `font-display:block;src:url('${base}${row.arabic}') format('woff2');` +
      `unicode-range:${LABEL_FONT_ARABIC_RANGE};}` +
      `@font-face{font-family:'${f.family}';font-style:normal;font-weight:${row.weight};` +
      `font-display:block;src:url('${base}${row.latin}') format('woff2');}`;
  });
  return css;
}

