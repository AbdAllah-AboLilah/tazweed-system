// تسخين: ننزّل الخط مرة واحدة أول ما النظام يفتح
// ============================================================
// ⚠️ مش شرط — كل مسار طباعة بيستنى الخط بنفسه قبل ما يرسم. ده عشان
// أول طبعة بعد فتح النظام ماتستناش، مش عشان الصح.
//
// ⚠️⚠️ ومابينزّلش حاجة لو الإعداد على "خط الجهاز" (الافتراضي) —
// activeLabelFont بترجّع null فـensureLabelFontReady بتخرج على طول.
if (typeof window !== 'undefined' && typeof window.addEventListener === 'function') {
  window.addEventListener('load', () => {
    try {
      ensureLabelFontReady();
    } catch (err) {
      /* تجاهل — الطباعة بتستنى الخط بنفسها */
    }
  });
}
